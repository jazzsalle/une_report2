-- 2. 0042 §2의 주석을 바로잡는다 (이중검토 M-8).
--
--   0042는 `journal_projection_item.section_key`가 "`document_block`의
--   `stable_block_key`와 같은 값"이라고 단언했다. **사실이 아니다.**
