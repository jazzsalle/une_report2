-- 0044 journal.event_types — 생성범위 필터를 저장한다 (CC-300 이중검토 C-3).
--
-- 무엇이 잘못됐나.
--   UNE-JNL-005는 `eventTypes`로 담을 이벤트 종류를 고를 수 있다. 그런데 그
--   필터를 어디에도 저장하지 않아서, 생성 시 해시는 **필터를 적용해** 접고
--   이후 드리프트 판정과 사실 갱신은 **무필터로** 다시 접었다. 필터가 한
--   건이라도 걸러냈다면 두 해시는 반드시 다르다. 결과는:
--
--     * 만들자마자 `drifted: true` — 아무 일도 일어나지 않았는데.
--     * 사실 갱신을 누르면 **사용자가 고른 범위가 말없이 전체로 넓어지고**
--       그 상태가 "정상"으로 확정된다.
--
--   즉 필터를 쓰는 순간 일지가 망가졌다. 계약과 화면은 이 필드를 공개하고
--   있었고, 어떤 시험도 값을 넣어 보지 않았다.
--
-- 왜 컬럼인가.
--   재투영은 "그때 무엇을 담기로 했는가"를 알아야 같은 것을 다시 접는다.
--   기간(`period_start`/`period_end`)을 저장하는 것과 같은 이유다 — 범위를
--   정하는 입력은 전부 일지에 남아야 재현이 성립한다(US-SIT-030 완료조건
--   "입력범위·query hash·event count 재현").
--
-- 빈 배열의 뜻.
--   `'{}'`는 "전부"다. 기존 행은 필터 없이 만들어졌으므로 기본값이 곧 사실이다.

ALTER TABLE journal
  ADD COLUMN IF NOT EXISTS event_types text[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN journal.event_types IS
  '담기로 한 이벤트 종류(UNE-JNL-005 eventTypes). 빈 배열은 전부. '
  '재투영·드리프트 판정이 같은 범위로 다시 접기 위해 저장한다(0044).';

